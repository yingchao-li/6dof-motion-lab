def translate(key: str, language: str = "en", **values: object) -> str:
    """Translate a key and interpolate named values."""

    catalog = TEXTS.get(key)
    if catalog is None:
        raise KeyError(f"Unknown translation key: {key}")
    text = catalog.get(language, catalog["en"])
    return text.format(**values) if values else text
